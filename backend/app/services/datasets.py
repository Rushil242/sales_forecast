"""Dataset registry: bundled files, uploads, and connected accounts.

Three ways a dataset reaches the API -- it ships with the repo, the user uploads a
CSV, or a connector pulled it live from the retailer's own Shopify or Zoho. All
three end up as the same :class:`Dataset`, so every endpoint downstream is
indifferent to which. That uniformity is load-bearing: live Shopify data faces the
same data-quality gate and the same refusal to forecast a too-short series as a
hand-made CSV does.

Uploads are held in an in-process LRU rather than written to disk. Connector syncs
*are* written to disk, because the user explicitly authorised us to hold that data
and re-pulling it on every request would hammer the platform's API.
"""

from __future__ import annotations

import logging
import threading
from collections import OrderedDict
from dataclasses import dataclass
from pathlib import Path

import pandas as pd

from app.config import get_settings
from app.core.errors import DatasetNotFoundError
from app.schemas.forecast import DatasetDetail, DatasetSummary
from app.services.ingestion import Dataset, build_dataset, load_csv

LOG = logging.getLogger(__name__)

MAX_CACHED_UPLOADS = 8


@dataclass(frozen=True)
class BundledDataset:
    key: str
    filename: str
    title: str
    description: str


BUNDLED = (
    BundledDataset(
        key="online-retail-ii",
        filename="retail_transactions.csv",
        title="Online Retail II (UCI)",
        description=(
            "Real transactions from a UK-based online giftware retailer, "
            "2009-12-01 to 2011-12-09, curated to the 30 products with the densest "
            "daily coverage. Source: UCI Machine Learning Repository, "
            "doi.org/10.24432/C5CG6D."
        ),
    ),
    BundledDataset(
        key="india-apparel",
        filename="india_apparel.csv",
        title="Indian apparel chain (simulated)",
        description=(
            "SIMULATED, NOT OBSERVED. A fast-fashion chain across eight Indian metros: "
            "20 clothing lines, 2024-09 to 2026-08. Generated by "
            "scripts/build_india_catalogue.py with real city climates, the Indian "
            "festival calendar and a consumer weekend uplift written into demand. "
            "Use it to see the product on Indian apparel; quote the bundled UCI file "
            "for any claim about measured accuracy, because this one's patterns were "
            "put there deliberately."
        ),
    ),
    BundledDataset(
        key="zara-mens",
        filename="Zara_Mens_Sales_Data.csv",
        title="Zara Menswear sample (15 days)",
        description=(
            "The original 15-day sample. Retained for schema-compatibility testing. "
            "Too short to support a 30-day forecast: requesting one returns an "
            "insufficient-data error rather than a padded result."
        ),
    ),
)

_upload_cache: OrderedDict[str, Dataset] = OrderedDict()
_bundled_cache: dict[str, Dataset] = {}
# Keyed by identifier, holding (file mtime, dataset) so a fresh sync invalidates
# the cache without anyone having to remember to clear it.
_connector_cache: dict[str, tuple[float, Dataset]] = {}
_lock = threading.Lock()


def _data_path(filename: str) -> Path:
    return get_settings().data_dir / filename


def list_bundled() -> list[DatasetSummary]:
    summaries: list[DatasetSummary] = []
    for entry in BUNDLED:
        if not _data_path(entry.filename).exists():
            continue
        try:
            summaries.append(_summarise(load_bundled(entry.key), entry, "bundled"))
        except Exception as exc:
            LOG.warning("Could not summarise bundled dataset %s: %s", entry.key, exc)
    return summaries


def load_bundled(key: str) -> Dataset:
    with _lock:
        if key in _bundled_cache:
            return _bundled_cache[key]

    entry = next((e for e in BUNDLED if e.key == key), None)
    if entry is None:
        raise DatasetNotFoundError(
            f"Unknown dataset '{key}'.", available=[e.key for e in BUNDLED]
        )

    path = _data_path(entry.filename)
    if not path.exists():
        raise DatasetNotFoundError(
            f"Dataset file '{entry.filename}' is missing. "
            "Run `python -m scripts.build_dataset --out ../data` to rebuild it.",
            expected_path=str(path),
        )

    dataset = build_dataset(pd.read_csv(path), entry.title)
    with _lock:
        _bundled_cache[key] = dataset
    return dataset


def store_upload(content: bytes, filename: str) -> tuple[str, Dataset]:
    """Ingest an uploaded CSV and cache it under a token the client reuses."""
    dataset = load_csv(content, filename)
    token = f"upload:{dataset.fingerprint()}"
    with _lock:
        _upload_cache[token] = dataset
        _upload_cache.move_to_end(token)
        while len(_upload_cache) > MAX_CACHED_UPLOADS:
            evicted, _ = _upload_cache.popitem(last=False)
            LOG.info("Evicted cached upload %s", evicted)
    return token, dataset


def load_connector(identifier: str) -> Dataset:
    """Load the CSV a connector sync wrote for one connected account.

    Connector data enters through exactly the same door as an upload. There is no
    fast path that skips the schema resolution or the cleaning, so a Shopify sync
    with unparsable dates loses those rows and says so, just like a CSV would.
    """
    from app.services.connectors.service import dataset_path

    account_id = identifier.split(":", 1)[1]
    path = dataset_path(account_id)
    if not path.exists():
        raise DatasetNotFoundError(
            "That connected account has not been synced yet. Open Connect data and "
            "press Sync, then try again.",
            account_id=account_id,
        )

    with _lock:
        cached = _connector_cache.get(identifier)
    stamp = path.stat().st_mtime
    if cached and cached[0] == stamp:
        return cached[1]

    dataset = build_dataset(pd.read_csv(path), _connector_label(account_id))
    with _lock:
        _connector_cache[identifier] = (stamp, dataset)
    return dataset


def _connector_label(account_id: str) -> str:
    """The account's own name, so the UI shows 'RetailIQ Demo Store', not a uuid."""
    from app.db.models import ConnectorAccount
    from app.db.session import session_scope

    try:
        with session_scope() as session:
            account = session.get(ConnectorAccount, account_id)
            if account is not None:
                return f"{account.label}"
    except Exception as exc:  # pragma: no cover - a label is never worth failing over
        LOG.debug("Could not read connector label for %s: %s", account_id, exc)
    return f"Connected account {account_id[:8]}"


def list_connected() -> list[DatasetSummary]:
    """Summarise every connected account that has actually been synced."""
    from app.db.models import ConnectorAccount
    from app.db.session import session_scope
    from app.services.connectors.registry import get as get_spec

    summaries: list[DatasetSummary] = []
    try:
        with session_scope() as session:
            accounts = session.query(ConnectorAccount).all()
            rows = [(a.id, a.provider, a.label, a.last_sync_rows,
                     a.last_sync_at.isoformat() if a.last_sync_at else None)
                    for a in accounts]
    except Exception as exc:
        LOG.warning("Could not list connected accounts: %s", exc)
        return []

    for account_id, provider, label, synced_rows, synced_at in rows:
        if not synced_rows:
            continue
        identifier = f"connector:{account_id}"
        try:
            dataset = load_connector(identifier)
        except Exception as exc:
            LOG.warning("Connected account %s could not be loaded: %s", account_id, exc)
            continue
        spec = get_spec(provider)
        summary = _summarise(dataset, None, "connector")
        summary.name = identifier
        summary.description = (
            f"Live order history pulled from {spec.name if spec else provider} "
            f"account '{label}'"
            + (f", last synced {synced_at[:10]}." if synced_at else ".")
        )
        summary.connector = {
            "account_id": account_id,
            "provider": provider,
            "label": label,
        }
        summaries.append(summary)
    return summaries


def resolve(identifier: str) -> Dataset:
    """Resolve a dataset key, upload token or connector reference to a dataset."""
    if identifier.startswith("connector:"):
        return load_connector(identifier)
    if identifier.startswith("upload:"):
        with _lock:
            dataset = _upload_cache.get(identifier)
            if dataset is not None:
                _upload_cache.move_to_end(identifier)
        if dataset is None:
            raise DatasetNotFoundError(
                "That uploaded dataset is no longer cached. Please upload the file again.",
                token=identifier,
            )
        return dataset
    return load_bundled(identifier)


def _summarise(dataset: Dataset, entry: BundledDataset | None, source: str) -> DatasetSummary:
    frame = dataset.frame
    return DatasetSummary(
        name=entry.key if entry else dataset.name,
        source=source,  # type: ignore[arg-type]
        rows=len(frame),
        products=int(frame["product"].nunique()),
        regions=dataset.regions()[:50],
        first_date=frame["date"].min().strftime("%Y-%m-%d"),
        last_date=frame["date"].max().strftime("%Y-%m-%d"),
        span_days=int((frame["date"].max() - frame["date"].min()).days) + 1,
        columns=sorted(dataset.column_map.values()),
        description=(
            entry.description if entry
            else f"Uploaded file '{dataset.name}'."
        ),
    )


def describe(identifier: str) -> DatasetDetail:
    from app.services.forecast_service import summarise_products

    dataset = resolve(identifier)
    entry = next((e for e in BUNDLED if e.key == identifier), None)
    if identifier.startswith("upload:"):
        source = "upload"
    elif identifier.startswith("connector:"):
        source = "connector"
    else:
        source = "bundled"
    summary = _summarise(dataset, entry, source)
    return DatasetDetail(
        **summary.model_dump(),
        product_list=summarise_products(dataset),  # type: ignore[arg-type]
    )
